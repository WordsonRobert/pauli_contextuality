"""Integrality cascade: find a line-orbit O of a subgroup H <= O^-(8,2) that contains a doily.
Then deg(O) >= ceil(|O|/5) by transfer inside O (H transitive on O), and transfer of O into Q-(7,2)
(O^-(8,2) line-transitive) gives deg Q-(7,2) >= ceil(1071 * ceil(|O|/5) / |O|)."""
import numpy as np, itertools, random, math, sys
from geometry import geometry
from engine import omega
random.seed(7)
pts, lines, signs = geometry("Q-", 4)
key = {p.tobytes(): i for i, p in enumerate(pts)}
lineidx = {l: i for i, l in enumerate(lines)}
q = lambda p: (int(p[:4] @ p[4:]) + int(p[0]) + int(p[4])) % 2
V8 = [np.array(v, dtype=np.uint8) for v in itertools.product([0, 1], repeat=8) if any(v)]
nons = [v for v in V8 if q(v) == 1]; sing = [v for v in V8 if q(v) == 0]
def refl(c):
    return [key[((p + omega(p, c) * c) % 2).astype(np.uint8).tobytes()] for p in pts]
def orbits(gens):
    parent = list(range(len(lines)))
    def f(i):
        while parent[i] != i: parent[i] = parent[parent[i]]; i = parent[i]
        return i
    for g in gens:
        for i, l in enumerate(lines):
            j = lineidx[tuple(sorted(g[v] for v in l))]
            a, b = f(i), f(j)
            if a != b: parent[a] = b
    groups = {}
    for i in range(len(lines)): groups.setdefault(f(i), []).append(i)
    return list(groups.values())
def random_doily():
    while True:
        c = random.choice(nons)
        perpc = [v for v in V8 if omega(v, c) == 0 and not np.array_equal(v, c)]
        u1 = random.choice(perpc); u2 = random.choice([v for v in perpc if omega(v, u1) == 1])
        rest = [v for v in perpc if omega(v, u1) == 0 and omega(v, u2) == 0]
        u3 = random.choice(rest); cand = [v for v in rest if omega(v, u3) == 1]
        if not cand: continue
        u4 = random.choice(cand)
        span = set()
        for co in itertools.product([0, 1], repeat=5):
            w = sum(ci * bi for ci, bi in zip(co, [c, u1, u2, u3, u4])) % 2
            if w.any(): span.add(w.astype(np.uint8).tobytes())
        L = [i for i, l in enumerate(lines) if all(pts[v].tobytes() in span for v in l)]
        if len(L) == 15: return frozenset(L)
doilies = [random_doily() for _ in range(int(sys.argv[1]) if len(sys.argv) > 1 else 3000)]
print("sampled doilies", len(doilies), flush=True)
def span_vecs(basis):
    out = []
    for co in itertools.product([0, 1], repeat=len(basis)):
        w = sum(ci * bi for ci, bi in zip(co, basis)) % 2
        if w.any(): out.append(w)
    return out
# candidate subgroups: generated by reflections in non-singular vectors of X and of X^perp, for various X
cands = {}
a = nons[0]; b = next(v for v in nons if omega(a, v) == 1 and q((a + v) % 2) == 1)
p0 = sing[0]; p1 = next(v for v in sing if omega(v, p0) == 1)
cands["E aniso"] = [a, b]
cands["a nonsing"] = [a]
cands["p sing"] = [p0]
cands["H hyp plane"] = [p0, p1]
c2 = next(v for v in nons if omega(v, a) == 0 and not np.array_equal(v, a))
cands["<a,c> nondeg? (perp nons)"] = [a, c2]
s2 = next(v for v in sing if omega(v, p0) == 0 and not np.array_equal(v, p0))
cands["t.s. line"] = [p0, s2]
cands["a + p perp"] = [a, next(v for v in sing if omega(v, a) == 0)]
best = None
for name, X in cands.items():
    Xs = span_vecs(X)
    gens = [refl(c) for c in nons if all(omega(c, x) == 0 for x in X)] + [refl(c) for c in Xs if q(c) == 1]
    orbs = orbits(gens)
    for O in orbs:
        Oset = set(O)
        cont = [D for D in doilies if D <= Oset]
        if cont:
            lb = math.ceil(len(O) / 5); r = lb / len(O)
            up = math.ceil(1071 * lb / len(O))
            print(f"{name:28s} orbit |O|={len(O):4d}  contains {len(cont)} sampled doilies  deg(O)>={lb}  ratio {r:.5f}  => deg Q-(7,2) >= {up}", flush=True)
            if best is None or up > best[0]: best = (up, name, sorted(O), sorted(next(iter(cont))))
        else:
            print(f"{name:28s} orbit |O|={len(O):4d}  (no sampled doily inside)", flush=True)
import json
json.dump({"bound": best[0], "group": best[1], "orbit": best[2], "doily": best[3]}, open("cascade_best.json", "w"))
print("BEST", best[0], best[1])
