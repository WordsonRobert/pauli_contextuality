"""Iterated integrality cascade on Q-(7,2).
Facts used (all rigorous):
 * a doily sub-configuration has degree 3 (15 lines);
 * if H <= Aut(O) is transitive on the line set O and C is a sub-configuration of O, then
   deg O >= ceil(|O| * deg C / |C|)   (transfer theorem);
 * Q-(7,2) itself is line-transitive under O^-(8,2).
Orbits O are orbits of groups generated by orthogonal reflections, hence H is transitive on O."""
import numpy as np, itertools, random, math, sys, json
from fractions import Fraction as Fr
from geometry import geometry
from engine import omega
random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 3)
pts, lines, signs = geometry("Q-", 4)
key = {p.tobytes(): i for i, p in enumerate(pts)}
lineidx = {l: i for i, l in enumerate(lines)}
q = lambda p: (int(p[:4] @ p[4:]) + int(p[0]) + int(p[4])) % 2
V8 = [np.array(v, dtype=np.uint8) for v in itertools.product([0, 1], repeat=8) if any(v)]
nons = [v for v in V8 if q(v) == 1]
REFL = {}
def refl(c):
    k = c.tobytes()
    if k not in REFL:
        REFL[k] = [key[((p + omega(p, c) * c) % 2).astype(np.uint8).tobytes()] for p in pts]
    return REFL[k]
def orbits(gens):
    parent = list(range(len(lines)))
    def f(i):
        while parent[i] != i: parent[i] = parent[parent[i]]; i = parent[i]
        return i
    for g in gens:
        for i, l in enumerate(lines):
            j = lineidx[tuple(sorted(g[v] for v in l))]
            a, b = f(i), f(j)
            if a != b: parent[a] = b
    groups = {}
    for i in range(len(lines)): groups.setdefault(f(i), []).append(i)
    return [frozenset(g) for g in groups.values()]
def span(basis):
    out = []
    for co in itertools.product([0, 1], repeat=len(basis)):
        w = sum(ci * bi for ci, bi in zip(co, basis)) % 2
        if w.any(): out.append(w.astype(np.uint8))
    return out
def random_doily():
    while True:
        c = random.choice(nons)
        perpc = [v for v in V8 if omega(v, c) == 0 and not np.array_equal(v, c)]
        u1 = random.choice(perpc); u2 = random.choice([v for v in perpc if omega(v, u1) == 1])
        rest = [v for v in perpc if omega(v, u1) == 0 and omega(v, u2) == 0]
        u3 = random.choice(rest); cand = [v for v in rest if omega(v, u3) == 1]
        if not cand: continue
        u4 = random.choice(cand)
        S = {w.tobytes() for w in span([c, u1, u2, u3, u4])}
        L = [i for i, l in enumerate(lines) if all(pts[v].tobytes() in S for v in l)]
        if len(L) == 15: return frozenset(L)
NDOIL = int(sys.argv[1]) if len(sys.argv) > 1 else 4000
doilies = list({random_doily() for _ in range(NDOIL)})
# subgroups: for random subspaces X (dim 1..4), H_X = < t_c : c nonsingular, c in X^perp >  (+ optionally t_c, c in X)
configs = {}   # frozenset -> (Fraction lower bound on ratio, provenance)
for D in doilies: configs[D] = (Fr(3, 15), "doily")
nsub = int(sys.argv[3]) if len(sys.argv) > 3 else 60
for trial in range(nsub):
    d = random.choice([1, 1, 2, 2, 2, 3, 3, 4])
    X = [nons[0]] + random.sample(V8, d - 1) if random.random() < 0.7 else random.sample(V8, d)
    Xs = span(X)
    perp_nons = [c for c in nons if all(omega(c, x) == 0 for x in X)]
    for with_inner in (False, True):
        gens = [refl(c) for c in perp_nons] + ([refl(c) for c in Xs if q(c) == 1] if with_inner else [])
        if not gens: continue
        for O in orbits(gens):
            if O not in configs and len(O) >= 15:
                configs[O] = (Fr(0), f"orbit dimX={d} inner={with_inner}")
print("configs:", len(configs), "of which orbits:", sum(1 for v in configs.values() if v[1] != 'doily'), flush=True)
items = list(configs.keys())
orbs = [O for O in items if configs[O][1] != "doily"]
# fixpoint iteration
changed = True; rounds = 0
while changed and rounds < 10:
    changed = False; rounds += 1
    for O in orbs:
        best = configs[O][0]
        for C in items:
            if len(C) < len(O) and configs[C][0] > 0 and C <= O:
                r = Fr(math.ceil(len(O) * configs[C][0]), len(O))
                if r > best:
                    best = r; prov = C
        if best > configs[O][0]:
            configs[O] = (best, configs[O][1]); changed = True
    top = max(configs[O][0] for O in orbs)
    print(f"round {rounds}: best orbit ratio {float(top):.6f} -> deg Q-(7,2) >= {math.ceil(1071 * top)}", flush=True)
top = max(orbs, key=lambda O: configs[O][0])
print("BEST orbit size", len(top), "ratio", configs[top][0], "->", math.ceil(1071 * configs[top][0]))
