# Run from lean/:  python3 scripts/extract_theorems.py   (rewrites THEOREMS.md)
import re, os, sys
# modules in dependency order, read from the library root (the axiom audit module is skipped)
files = [l.split(".")[-1].strip() for l in open("PauliContextuality.lean")
         if l.startswith("import PauliContextuality.")]
files = [f for f in files if f != "Audit"]
out = []; total = 0; nat = 0
for f in files:
    src = open(f"PauliContextuality/{f}.lean").read()
    lines = src.split("\n")
    items = []
    i = 0
    while i < len(lines):
        m = re.match(r'^(?:private\s+)?(theorem|lemma)\s+(\S+)', lines[i])
        if m:
            # docstring above
            doc = []
            j = i - 1
            if j >= 0 and lines[j].strip().endswith("-/"):
                k = j
                while k >= 0 and "/--" not in lines[k]: k -= 1
                doc = [l.strip() for l in lines[k:j+1]]
            stmt = [lines[i]]
            k = i
            def ends(l):
                t = l.strip()
                return ":=" in l and not t.startswith("let ") and not re.match(r"^\(?\w+\s*:.*:=", t) or t.endswith(":= by")
            while not ends(stmt[-1]) and k + 1 < len(lines):
                k += 1; stmt.append(lines[k])
            last = stmt[-1]
            cut = last.rfind(":= by") if ":= by" in last else last.index(":=")
            stmt[-1] = last[:cut].rstrip()
            s = "\n".join(stmt).rstrip()
            # proof body to detect native_decide
            body_end = k + 1
            while body_end < len(lines) and not re.match(r'^(theorem|lemma|def|noncomputable|/--|structure|instance|abbrev|end |namespace|section|open|variable|@\[|private)', lines[body_end]):
                body_end += 1
            body = "\n".join(lines[k:body_end])
            nd = "native_decide" in body
            items.append((m.group(2), " ".join(d.replace("/--","").replace("-/","").strip() for d in doc).strip(), s, nd))
            i = k + 1
        else:
            i += 1
    total += len(items); nat += sum(x[3] for x in items)
    out.append((f, items))
with open("THEOREMS.md", "w") as w:
    w.write(f"# All mechanically proved theorems ({total} theorems/lemmas, {len(files)} modules)\n\n")
    w.write("Extracted verbatim from the Lean sources (statement up to `:=`). ⚙ = the proof itself calls "
            f"`native_decide` ({nat} of them; compiler-trusted finite computation). A theorem without ⚙ may still "
            "depend on a ⚙ lemma; the exact axiom footprint of every headline theorem is printed by the axiom "
            "audit (`PauliContextuality/Audit.lean`, run by `scripts/check_all.sh`). No `sorry`.\n\n"
            "Generated by `scripts/extract_theorems.py`.\n\n")
    for f, items in out:
        w.write(f"## {f}.lean ({len(items)})\n\n")
        for name, doc, s, nd in items:
            w.write(f"### `{name}`{' ⚙' if nd else ''}\n")
            if doc: w.write(f"{doc}\n")
            w.write(f"```lean\n{s}\n```\n\n")
print(total, nat)
